# Prepare the controlled AAA cohort before author-reviewed cell annotation.
source(file.path("R", "common.R"))
require_packages(c("Seurat", "harmony"))
manifest <- project_path("data", "restricted", "aaa_samples.tsv")
if (!file.exists(manifest)) stop("Missing sample manifest: ", manifest)
samples <- read.delim(manifest, stringsAsFactors = FALSE)
if (!all(c("sample_id", "disease_status", "matrix_dir") %in% names(samples)))
  stop("Manifest needs sample_id, disease_status, matrix_dir")
if (anyDuplicated(samples$sample_id) || nrow(samples) != 10L)
  stop("Expected 10 unique samples: seven AAA and three controls")
if (!identical(as.integer(table(factor(samples$disease_status, levels = c("AAA", "Control")))), c(7L, 3L)))
  stop("Expected seven AAA and three control samples")
objects <- lapply(seq_len(nrow(samples)), function(i) {
  folder <- samples$matrix_dir[i]
  if (!dir.exists(folder)) stop("Missing 10x folder: ", folder)
  counts <- Seurat::Read10X(folder)
  if (is.list(counts)) counts <- counts[[1]]
  x <- Seurat::CreateSeuratObject(counts = counts, project = samples$sample_id[i],
                                 min.cells = 3, min.features = 200)
  x$sample_id <- samples$sample_id[i]
  x$disease_status <- samples$disease_status[i]
  x[["percent.mt"]] <- Seurat::PercentageFeatureSet(x, pattern = "^MT-")
  subset(x, subset = nFeature_RNA > 200 & nFeature_RNA < 7500 & percent.mt < 20)
})
names(objects) <- samples$sample_id
obj <- merge(objects[[1]], y = objects[-1], add.cell.ids = names(objects), project = "AAA_AS")
doublet_file <- project_path("data", "restricted", "doublet_cell_ids.txt")
if (!file.exists(doublet_file)) stop("Supply a reviewed doublet_cell_ids.txt, even if empty")
doublets <- readLines(doublet_file, warn = FALSE)
if (length(doublets)) obj <- subset(obj, cells = setdiff(colnames(obj), doublets))
obj <- Seurat::NormalizeData(obj)
obj <- Seurat::FindVariableFeatures(obj)
data("cc.genes.updated.2019", package = "Seurat", envir = environment())
cc <- get("cc.genes.updated.2019", envir = environment())
s <- intersect(cc$s.genes, rownames(obj)); g2m <- intersect(cc$g2m.genes, rownames(obj))
if (length(s) < 10 || length(g2m) < 10) stop("Insufficient cell-cycle genes for scoring")
obj <- Seurat::CellCycleScoring(obj, s.features = s, g2m.features = g2m)
obj <- Seurat::ScaleData(obj, vars.to.regress = c("percent.mt", "S.Score", "G2M.Score"))
obj <- Seurat::RunPCA(obj, npcs = 30)
obj <- harmony::RunHarmony(obj, group.by.vars = "sample_id", reduction.use = "pca")
obj <- Seurat::FindNeighbors(obj, reduction = "harmony", dims = 1:30)
obj <- Seurat::FindClusters(obj, resolution = 0.6)
obj <- Seurat::RunUMAP(obj, reduction = "harmony", dims = 1:30)
obj <- Seurat::RunTSNE(obj, reduction = "harmony", dims = 1:30)
out <- project_path("data", "restricted", "aaa_clustered.rds")
saveRDS(obj, out)
markers <- Seurat::FindAllMarkers(obj, only.pos = TRUE)
write_table(markers, project_path("results", "single_cell", "cluster_markers.tsv"))
message("Review cluster markers and provide cell-level annotations before CellChat: ", out)
